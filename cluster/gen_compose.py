"""Generate a docker-compose.yml for an N-node CRDT analytics cluster.

Usage:
    python cluster/gen_compose.py --nodes N [--gossip-interval X] [--fanout Y]

Constraints:
    4 <= N <= 10  (exits with code 2 otherwise)

Output file: docker-compose.yml in the project root (cwd).
"""

from __future__ import annotations

import argparse
import os
import sys

# --- YAML serialiser (stdlib only, no pyyaml needed) -----------------------

def _yaml_str(value: str) -> str:
    """Quote a YAML string value if it contains special characters."""
    # Always single-quote env-var strings to prevent YAML misinterpretation
    return f"'{value}'"


def _write_compose(n: int, gossip_interval: float, fanout: int, path: str) -> None:
    """Write a docker-compose.yml file for an N-node cluster."""

    lines: list[str] = [
        "# Generated by cluster/gen_compose.py -- DO NOT EDIT",
        f"# Nodes: {n}  gossip_interval: {gossip_interval}s  fanout: {fanout}",
        "",
        "name: crdt-tracker",
        "",
        "networks:",
        "  crdt-net:",
        "    driver: bridge",
        "    name: crdt-net",
        "",
        "services:",
    ]

    for i in range(1, n + 1):
        node_id = f"node{i}"
        host_port = 5000 + i  # node1 -> 5001, node2 -> 5002, ...

        # Build PEERS string: all other nodes via http://nodeX:5000
        peers_parts = [
            f"node{j}=http://node{j}:5000"
            for j in range(1, n + 1)
            if j != i
        ]
        peers_str = ",".join(peers_parts)

        lines += [
            f"  {node_id}:",
            f"    build: .",
            f"    container_name: {node_id}",
            f"    hostname: {node_id}",
            f"    init: true",
            f"    restart: unless-stopped",
            f"    stop_grace_period: 10s",
            f"    networks:",
            f"      - crdt-net",
            f"    ports:",
            f"      - '{host_port}:5000'",
            f"    environment:",
            f"      NODE_ID: {node_id}",
            f"      HOST: 0.0.0.0",
            f"      PORT: '5000'",
            f"      PEERS: '{peers_str}'",
            f"      GOSSIP_INTERVAL: '{gossip_interval}'",
            f"      FANOUT: '{fanout}'",
            f"      DATA_DIR: /data",
            f"      METRICS: page_views,clicks",
            f"    volumes:",
            f"      - ./data/{node_id}:/data",
            f"    healthcheck:",
            f"      test:",
            f"        - CMD",
            f"        - python",
            f"        - -c",
            f"        - \"import urllib.request, sys; r=urllib.request.urlopen('http://localhost:5000/health', timeout=2); sys.exit(0 if r.status==200 else 1)\"",
            f"      interval: 5s",
            f"      timeout: 3s",
            f"      start_period: 5s",
            f"      retries: 3",
            "",
        ]

    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"Generated {path} ({n} nodes, gossip_interval={gossip_interval}s, fanout={fanout})")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description="Generate docker-compose.yml for CRDT analytics cluster",
    )
    parser.add_argument(
        "--nodes", "-n",
        type=int,
        required=True,
        help="Number of nodes (4-10)",
    )
    parser.add_argument(
        "--gossip-interval",
        type=float,
        default=1.0,
        metavar="SECONDS",
        help="Gossip interval in seconds (default: 1.0)",
    )
    parser.add_argument(
        "--fanout",
        type=int,
        default=2,
        help="Gossip fanout (default: 2)",
    )
    parser.add_argument(
        "--output",
        default="docker-compose.yml",
        help="Output file path (default: docker-compose.yml)",
    )

    args = parser.parse_args(argv)

    if args.nodes < 4 or args.nodes > 10:
        print(
            f"ERROR: --nodes must be between 4 and 10, got {args.nodes}",
            file=sys.stderr,
        )
        sys.exit(2)

    output_path = args.output
    _write_compose(args.nodes, args.gossip_interval, args.fanout, output_path)


if __name__ == "__main__":
    main()
